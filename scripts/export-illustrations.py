"""Generate bilingual figure metadata and English SVGs from tracked Japanese SVGs.

No font, graphics package, network, or build step is needed to read the site.
Run this script only when editing illustrations.json or the Japanese originals.
"""
from pathlib import Path
import json,re,xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[1]
data=json.loads((ROOT/'scripts/illustrations.json').read_text())
folder=ROOT/'docs/illustrations'
ET.register_namespace('', 'http://www.w3.org/2000/svg')
for fig in data['figures']:
    source=folder/(fig['id']+'-ja.svg')
    tree=ET.parse(source);svg=tree.getroot()
    svg.set('style','max-width:100%;height:auto')
    tree.write(source,encoding='utf-8',xml_declaration=True)
    svg.set('lang','en');svg.set('{http://www.w3.org/XML/1998/namespace}lang','en')
    for el in svg.iter():
        if el.tag.endswith('}text') and re.search('[\u3040-\u30ff\u3400-\u9fff]',el.text or ''):
            assert el.text in data['labels'],(fig['id'],el.text)
            el.text=data['labels'][el.text]
    tree.write(folder/(fig['id']+'-en.svg'),encoding='utf-8',xml_declaration=True)

metadata=json.dumps(data['figures'],ensure_ascii=False,indent=2)
js='''/* Generated by scripts/export-illustrations.py; edit scripts/illustrations.json. */
(() => {
  'use strict';
  const figures = FIGURES;
  const escape = text => text.replace(/[&<>"']/g, char => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));
  function render(id, locale) {
    const figure = figures.find(item => item.id === id);
    if (!figure) throw new RangeError('Unknown illustration: ' + id);
    const lang = locale === 'en' ? 'en' : 'ja', i = lang === 'en' ? 1 : 0;
    const src = './illustrations/' + id + '-' + lang + '.svg?v=20261106-3';
    const enlarge = i ? 'View larger diagram' : '図を大きく見る';
    return `<figure class="concept-figure" data-illustration="${id}"><img src="${src}" width="1200" height="700" loading="lazy" decoding="async" alt="${escape(figure.alt[i])}"><figcaption><strong>${escape(figure.title[i])}</strong>${escape(figure.caption[i])}</figcaption><a class="figure-enlarge" href="${src}" target="_blank" rel="noopener noreferrer">${enlarge} ↗</a></figure>`;
  }
  window.AstroIllustrations = { figures, render };
})();
'''.replace('FIGURES',metadata)
(ROOT/'docs/illustrations.js').write_text(js)
print('Generated 10 bilingual illustrations and metadata.')
